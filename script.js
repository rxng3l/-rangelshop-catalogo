/* =========================================================
   PLACEHOLDER
========================================================= */

function createPlaceholder(product) {

    const canvas =
        document.createElement("canvas");


    canvas.width = 800;

    canvas.height = 980;


    const ctx =
        canvas.getContext("2d");


    ctx.fillStyle = "#eeeeeb";

    ctx.fillRect(
        0,
        0,
        canvas.width,
        canvas.height
    );


    ctx.beginPath();

    ctx.arc(
        400,
        390,
        190,
        0,
        Math.PI * 2
    );


    ctx.fillStyle = "#d7d7d2";

    ctx.fill();


    ctx.fillStyle = "#111";

    ctx.textAlign = "center";


    ctx.font =
        "800 72px Arial";


    ctx.fillText(
        "RЯ",
        400,
        410
    );


    ctx.font =
        "600 26px Arial";


    ctx.fillStyle = "#555";


    ctx.fillText(
        product.name,
        400,
        690
    );


    ctx.font =
        "500 18px Arial";


    ctx.fillStyle = "#999";


    ctx.fillText(
        product.category.toUpperCase(),
        400,
        735
    );


    return canvas.toDataURL(
        "image/png"
    );

}



/* =========================================================
   MOSTRAR PRODUCTOS
========================================================= */

function renderProducts() {

    const search =
        searchInput.value
            .toLowerCase()
            .trim();


    const filteredProducts =
        products.filter(
            product => {


                const matchesCategory =
                    currentCategory === "Todos" ||
                    product.category === currentCategory;


                const matchesSearch =
                    product.name
                        .toLowerCase()
                        .includes(search);


                return (
                    matchesCategory &&
                    matchesSearch
                );

            }
        );


    productsGrid.innerHTML = "";


    if (
        filteredProducts.length === 0
    ) {

        productsGrid.innerHTML = `

            <div class="no-products">

                No encontramos diseños
                con esa búsqueda.

            </div>

        `;

        return;
    }



    filteredProducts.forEach(
        product => {


            const card =
                document.createElement(
                    "article"
                );


            card.className =
                "product-card";


            const imageContainer =
                document.createElement(
                    "div"
                );


            imageContainer.className =
                "product-image";


            const image =
                document.createElement(
                    "img"
                );


            image.src =
                product.image;


            image.alt =
                product.name;


            image.loading =
                "lazy";


            image.onerror =
                () => {

                    image.onerror = null;

                    image.src =
                        createPlaceholder(
                            product
                        );

                };


            imageContainer.appendChild(
                image
            );



            const info =
                document.createElement(
                    "div"
                );


            info.className =
                "product-info";


            info.innerHTML = `

                <div class="product-category">

                    ${product.category}

                </div>


                <div class="product-title">

                    ${product.name}

                </div>


                <div class="product-price">

                    Desde $${product.price} MXN

                </div>

            `;


            card.appendChild(
                imageContainer
            );


            card.appendChild(
                info
            );



            card.addEventListener(
                "click",
                () => {

                    openProduct(
                        product
                    );

                }
            );


            productsGrid.appendChild(
                card
            );

        }
    );

}



